// Makes web-sized copies of the events' pictures: the originals are camera files of up to 8 MB each.
//
// 1. Posters, phone-sized:
//   sources: the poster (or image1 when poster is "") of each event in PastEvents.tsx, and the image of each
//            entry in currentPhase.ts
//   public<path>  ->  public/posters/<slug>.webp   (640px wide, webp)
//
// 2. Photos, page-sized: image1 to image4 of each event in PastEvents.tsx
//   public<path>  ->  public/event-photos/<slug>.webp   (1600px wide, webp)
//
// It also writes src/components/events/posterThumbs.ts, which maps each original path to its copy, for
// thumbOf() and photoOf() in posterThumb.ts. Run it again whenever the event data changes.
//
//   npm run posters
import { promises as fs } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const OUT_DIR = path.join(PUBLIC, "posters");
const EVENTS = path.join(ROOT, "src", "components", "events");
const PAST = path.join(EVENTS, "PastEvents.tsx");
const CURRENT = path.join(EVENTS, "currentPhase.ts");
const THUMBS_FILE = path.join(EVENTS, "posterThumbs.ts");

const WIDTH = 640;
const QUALITY = 72;
const PHOTO_DIR = path.join(PUBLIC, "event-photos");
const PHOTO_WIDTH = 1600;
const PHOTO_QUALITY = 76;

const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const kb = (bytes) => (bytes / 1024).toFixed(1);

// Local image paths used by the events data, de-duplicated, in order of appearance.
async function collectSources() {
  const past = await fs.readFile(PAST, "utf8");
  const current = await fs.readFile(CURRENT, "utf8");
  const found = [];
  // each event object has a `poster:` line followed by its `image1:` line; an empty poster falls back to image1
  for (const m of past.matchAll(/poster:\s*"([^"]*)"[\s\S]*?image1:\s*"([^"]*)"/g)) found.push(m[1] || m[2]);
  for (const m of current.matchAll(/\bimage:\s*"([^"]*)"/g)) found.push(m[1]);
  return [...new Set(found.filter((p) => p.startsWith("/")))];
}

// The photos on each event's own page.
async function collectPhotos() {
  const past = await fs.readFile(PAST, "utf8");
  const found = [...past.matchAll(/\bimage[1-4]:\s*"([^"]*)"/g)].map((m) => m[1]);
  return [...new Set(found.filter((p) => p.startsWith("/")))];
}

// Gives every source a unique slug; later sources with the same slug get "-2", "-3", ...
function assignSlugs(sources) {
  const used = new Set();
  return sources.map((src) => {
    const base = slugify(path.parse(src).name) || "poster";
    let slug = base;
    for (let i = 2; used.has(slug); i++) slug = `${base}-${i}`;
    used.add(slug);
    if (slug !== base) console.log(`  slug collision: ${src} -> ${slug}`);
    return { src, slug };
  });
}

// Converts every source into outDir and returns { original path: copy path }.
async function convert(sources, outDir, urlBase, width, quality) {
  const plan = assignSlugs(sources);
  await fs.mkdir(outDir, { recursive: true });

  const thumbs = {};
  let totalOrig = 0;
  let totalNew = 0;
  for (const { src, slug } of plan) {
    const input = path.join(PUBLIC, src.replace(/^\/+/, ""));
    let orig;
    try {
      orig = await fs.stat(input);
    } catch {
      console.warn(`  missing, skipped: public${src}`);
      continue;
    }
    const out = path.join(outDir, `${slug}.webp`);
    try {
      await sharp(input)
        .rotate() // honour EXIF orientation
        .resize({ width, withoutEnlargement: true })
        .webp({ quality })
        .toFile(out);
    } catch (err) {
      console.warn(`  failed, skipped: public${src}: ${err.message}`);
      continue;
    }
    const next = await fs.stat(out);
    thumbs[src] = `${urlBase}/${slug}.webp`;
    totalOrig += orig.size;
    totalNew += next.size;
    console.log(`  ${src}: ${kb(orig.size)} KB -> ${kb(next.size)} KB (${urlBase.slice(1)}/${slug}.webp)`);
  }
  console.log(`  = ${Object.keys(thumbs).length} files, ${(totalOrig / 1024 / 1024).toFixed(1)} MB original -> ${kb(totalNew)} KB\n`);
  return thumbs;
}

const entries = (map) =>
  Object.keys(map)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`);

async function main() {
  console.log("Posters");
  const thumbs = await convert(await collectSources(), OUT_DIR, "/posters", WIDTH, QUALITY);
  console.log("Photos");
  const photos = await convert(await collectPhotos(), PHOTO_DIR, "/event-photos", PHOTO_WIDTH, PHOTO_QUALITY);

  const body = [
    "// Generated by `npm run posters` (scripts/build-posters.mjs). Do not edit by hand.",
    "// Maps each event poster path to its phone-sized copy in public/posters/.",
    "export const POSTER_THUMBS: Record<string, string> = {",
    ...entries(thumbs),
    "};",
    "",
    "// Maps each event photo path to its page-sized copy in public/event-photos/.",
    "export const EVENT_PHOTOS: Record<string, string> = {",
    ...entries(photos),
    "};",
    "",
  ].join("\n");
  await fs.writeFile(THUMBS_FILE, body);
  console.log(`Map: ${path.relative(ROOT, THUMBS_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
