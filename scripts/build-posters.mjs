// Makes phone-sized copies of the event posters.
//
//   sources: the poster (or image1 when poster is "") of each event in PastEvents.tsx, and the image of each
//            entry in currentPhase.ts
//   public<path>  ->  public/posters/<slug>.webp   (640px wide, webp)
//
// It also writes src/components/events/posterThumbs.ts, which maps each original path to its copy, so the
// phone view can use thumbOf() from posterThumb.ts. Run it again whenever the event data changes.
//
//   npm run posters
import { promises as fs } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const OUT_DIR = path.join(PUBLIC, "posters");
const EVENTS = path.join(ROOT, "src", "components", "events");
const PAST = path.join(EVENTS, "PastEvents.tsx");
const CURRENT = path.join(EVENTS, "currentPhase.ts");
const THUMBS_FILE = path.join(EVENTS, "posterThumbs.ts");

const WIDTH = 640;
const QUALITY = 72;

const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const kb = (bytes) => (bytes / 1024).toFixed(1);

// Local image paths used by the events data, de-duplicated, in order of appearance.
async function collectSources() {
  const past = await fs.readFile(PAST, "utf8");
  const current = await fs.readFile(CURRENT, "utf8");
  const found = [];
  // each event object has a `poster:` line followed by its `image1:` line; an empty poster falls back to image1
  for (const m of past.matchAll(/poster:\s*"([^"]*)"[\s\S]*?image1:\s*"([^"]*)"/g)) found.push(m[1] || m[2]);
  for (const m of current.matchAll(/\bimage:\s*"([^"]*)"/g)) found.push(m[1]);
  return [...new Set(found.filter((p) => p.startsWith("/")))];
}

// Gives every source a unique slug; later sources with the same slug get "-2", "-3", ...
function assignSlugs(sources) {
  const used = new Set();
  return sources.map((src) => {
    const base = slugify(path.parse(src).name) || "poster";
    let slug = base;
    for (let i = 2; used.has(slug); i++) slug = `${base}-${i}`;
    used.add(slug);
    if (slug !== base) console.log(`  slug collision: ${src} -> ${slug}`);
    return { src, slug };
  });
}

async function main() {
  const plan = assignSlugs(await collectSources());
  await fs.mkdir(OUT_DIR, { recursive: true });

  const thumbs = {};
  let totalOrig = 0;
  let totalNew = 0;
  for (const { src, slug } of plan) {
    const input = path.join(PUBLIC, src.replace(/^\/+/, ""));
    let orig;
    try {
      orig = await fs.stat(input);
    } catch {
      console.warn(`  missing, skipped: public${src}`);
      continue;
    }
    const out = path.join(OUT_DIR, `${slug}.webp`);
    try {
      await sharp(input)
        .rotate() // honour EXIF orientation
        .resize({ width: WIDTH, withoutEnlargement: true })
        .webp({ quality: QUALITY })
        .toFile(out);
    } catch (err) {
      console.warn(`  failed, skipped: public${src}: ${err.message}`);
      continue;
    }
    const next = await fs.stat(out);
    thumbs[src] = `/posters/${slug}.webp`;
    totalOrig += orig.size;
    totalNew += next.size;
    console.log(`  ${src}: ${kb(orig.size)} KB -> ${kb(next.size)} KB (posters/${slug}.webp)`);
  }

  const lines = Object.keys(thumbs)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(thumbs[k])},`);
  const body = [
    "// Generated by `npm run posters` (scripts/build-posters.mjs). Do not edit by hand.",
    "// Maps each event poster path to its phone-sized copy in public/posters/.",
    "export const POSTER_THUMBS: Record<string, string> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
  await fs.writeFile(THUMBS_FILE, body);

  const n = Object.keys(thumbs).length;
  console.log(
    `\nTotal: ${n} posters, ${(totalOrig / 1024 / 1024).toFixed(1)} MB original -> ${kb(totalNew)} KB` +
      `\nThumbnails: public/posters/, map: ${path.relative(ROOT, THUMBS_FILE)}`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
